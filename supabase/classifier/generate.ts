// Turns dictionary.tsv and every dictionary.<lang>.tsv (languages.ts) into the migration that loads
// public.classifier_terms and public.catalog_words, and prints what each language covers.
// Usage: deno run --allow-read --allow-write generate.ts <migration.sql>
// Create the migration first (`supabase migration new classifier_dictionary_<n>`);
// a migration already on main is never edited.

import {
  type CatalogWord,
  coverage,
  type LanguageTerm,
  readTables,
} from "./languages.ts";

export const categories = [
  "produce",
  "bakery",
  "chilled",
  "meat",
  "pantry",
  "sweets",
  "drinks",
  "frozen",
  "household",
  "drugstore",
  "paint",
  "plumbing",
  "electrical",
  "tools",
  "fasteners",
  "building",
  "garden",
] as const;

export type Category = typeof categories[number];
export type Term = { term: string; category: Category };

/**
 * A term, synonym or language word: lower-case Latin words (Latin-1, Latin Extended-A, Romanian ș
 * and ț), as the tables' checks and public.item_key take them (20261126170003_item_key_letters.sql).
 */
export const termPattern = /^[a-zß-öø-ÿā-žșț]+( [a-zß-öø-ÿā-žșț]+)*$/u;

export function parseDictionary(tsv: string): Term[] {
  const seen = new Map<string, number>();
  const terms: Term[] = [];
  tsv.split("\n").forEach((raw, index) => {
    const line = raw.trimEnd();
    const at = `dictionary.tsv:${index + 1}`;
    if (line === "" || line.startsWith("#")) return;
    const [term, category, ...extra] = line.split("\t");
    if (term === undefined || category === undefined || extra.length > 0) {
      throw new Error(`${at}: expected "term<TAB>category"`);
    }
    if (!termPattern.test(term)) {
      throw new Error(`${at}: invalid term "${term}"`);
    }
    if (!(categories as readonly string[]).includes(category)) {
      throw new Error(`${at}: unknown category "${category}"`);
    }
    const first = seen.get(term);
    if (first !== undefined) {
      throw new Error(`${at}: "${term}" repeats line ${first}`);
    }
    seen.set(term, index + 1);
    terms.push({ term, category: category as Category });
  });
  return terms;
}

/**
 * What every generated classifier migration ends with (job 32a): the lexicon of folded forms and
 * synonyms is rebuilt from the new data, and so is every stored canonical key. Item rows are
 * updated with their triggers off: a new canonical key is not an edit.
 */
export const refreshLexicon = [
  "select public.refresh_classifier_lexicon();",
  "",
  "alter table public.items disable trigger user;",
  "update public.items set canonical_key = public.canonical_key(name);",
  "alter table public.items enable trigger user;",
  "",
].join("\n");

export function toMigration(
  terms: LanguageTerm[],
  words: CatalogWord[],
): string {
  const order = (a: string, b: string) => a < b ? -1 : a > b ? 1 : 0;
  const termRows = [...terms]
    .sort((a, b) => order(a.term, b.term))
    .map(({ term, category, lang }) =>
      `  ('${term}', '${category}', '${lang}')`
    );
  const wordRows = [...words]
    .sort((a, b) => order(a.lang, b.lang) || order(a.word, b.word))
    .map(({ lang, word, category }) =>
      `  ('${lang}', '${word}', '${category}')`
    );
  return [
    "-- Generated by supabase/classifier/generate.ts from supabase/classifier/dictionary.tsv and",
    "-- dictionary.<lang>.tsv. Edit the TSVs and generate a new migration; do not edit this file.",
    "",
    "truncate public.classifier_terms;",
    "",
    "insert into public.classifier_terms (term, category, lang) values",
    termRows.join(",\n") + ";",
    "",
    "delete from public.catalog_words;",
    "",
    ...(wordRows.length === 0 ? [] : [
      "insert into public.catalog_words (lang, word, category) values",
      wordRows.join(",\n") + ";",
      "",
    ]),
    refreshLexicon,
  ].join("\n");
}

export const dictionaryUrl = new URL("./dictionary.tsv", import.meta.url);
export const migrationsUrl = new URL("../migrations/", import.meta.url);

if (import.meta.main) {
  const [target] = Deno.args;
  if (!target) {
    console.error("usage: generate.ts <migration.sql>");
    Deno.exit(2);
  }
  const tables = await readTables();
  await Deno.writeTextFile(target, toMigration(tables.terms, tables.words));
  console.log(
    `${tables.terms.length} terms, ${tables.words.length} words -> ${target}`,
  );
  console.log(coverage(tables));
}
