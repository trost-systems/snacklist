// Writes round AI's recommendation as Markdown from the page's own words and measured.json.
// Usage: node approaches.mjs [en|de] > RECOMMENDATION.md
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { copy } from '../copy.js';
import { options } from '../options.js';

const lang = process.argv[2] === 'de' ? 'de' : 'en';
const here = dirname(fileURLToPath(import.meta.url));
const m = JSON.parse(readFileSync(join(here, '../measured.json'), 'utf8'));
const t = (v) => v[lang];
const md = (html) => html
  .replace(/<li>/g, '- ').replace(/<\/li>/g, '\n').replace(/<\/?ul>/g, '')
  .replace(/<\/?b>/g, '**').replace(/<\/?code>/g, '`').replace(/<p>/g, '').replace(/<\/p>/g, '\n\n')
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/\n{3,}/g, '\n\n').trim();
const f = (n, d = 1) => (lang === 'de' ? n.toFixed(d).replace('.', ',') : n.toFixed(d));
const rows = options.map((o) => {
  const v = m[o.id];
  return `| ${o.id} ${t(o.name)} | ${f(v.thinnest29)} / ${f(v.thinnest48)} px | ${f(v.monoThinnest29)} px | ${f(v.keyLight, 2)} / ${f(v.keyDark, 2)} | ${f(v.contrastLight.ratio, 2)} / ${f(v.contrastDark.ratio, 2)} | ${f(v.tileOnWall.light, 2)} | ${f(v.reachDp)} dp | ${t(o.keeps)} |`;
});
const out = `# ${t(copy.title)}

<!-- Generated by tools/approaches.mjs from copy.js, options.js and measured.json. Do not edit. -->

${md(t(copy.question))}

## ${t(copy.recHead)}

${md(t(copy.rec))}

## ${lang === 'de' ? 'Die Optionen' : 'The options'}

${options.map((o) => `- **${o.id} ${t(o.name)}**: ${t(o.what)}`).join('\n')}

## ${t(copy.measureHead)}

| ${copy.cols.map(t).join(' | ')} |
| ${copy.cols.map(() => '---').join(' | ')} |
${rows.join('\n')}

${md(t(copy.measureNotes).replace('{tintIos}', f(m.AI1.tinted.ios)).replace('{tintAL}', f(m.AI1.tinted.androidLight)).replace('{tintAD}', f(m.AI1.tinted.androidDark)))}

## ${t(copy.qHead)}

${md(t(copy.questions))}

## ${t(copy.swapHead)}

${md(t(copy.swap))}
`;
process.stdout.write(out);
