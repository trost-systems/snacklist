// Writes strings.js: every UI word the round takes from the app, copied from the ARB files by key, plus the new words
// the options propose (`proposed`, marked on the page with a dotted underline). verify.mjs checks strings.js against the
// ARB files.
// Usage: node tools/strings.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const here = dirname(fileURLToPath(import.meta.url));
export const keys = [
  'addFieldHint', 'tabList', 'tabHistory', 'tabMore', 'listEdit', 'itemsWord', 'shopRunning', 'shopEnd', 'priceAdd',
  'recentlyUsed', 'readd', 'tripTotal', 'subtotalsTotal', 'subtotalsUnpriced', 'moneyAtLeast', 'moneyEstimate',
];
export const proposed = {
  en: {
    ruHintTap: 'Tap an item to put it back on the list.',
    ruTicked: 'Ticked off',
    ruChipsHint: 'Need it again? Tap to put it back.',
    ruUntickHint: 'Tap a ticked item to untick it.',
    ruShowAll: 'Show all ({count})',
  },
  de: {
    ruHintTap: 'Tippe einen Artikel an, um ihn zurück auf die Liste zu setzen.',
    ruTicked: 'Abgehakt',
    ruChipsHint: 'Wieder gebraucht? Antippen holt es zurück.',
    ruUntickHint: 'Tippe einen abgehakten Artikel an, um ihn zurückzuholen.',
    ruShowAll: 'Alle zeigen ({count})',
  },
};
export const generate = (arbDir) => {
  const out = {};
  for (const lang of ['en', 'de']) {
    const arb = JSON.parse(readFileSync(join(arbDir, `app_${lang}.arb`), 'utf8'));
    out[lang] = Object.fromEntries(keys.map((k) => {
      if (!(k in arb)) throw new Error(`${k} is not in app_${lang}.arb`);
      return [k, arb[k]];
    }));
  }
  return `// Generated by tools/strings.mjs from app/l10n/app_<lang>.arb. Do not edit.\nexport const arb = ${JSON.stringify(out, null, 1)};\nexport const proposed = ${JSON.stringify(proposed, null, 1)};\n`;
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = generate(join(here, '../../../../app/l10n'));
  const file = join(here, '../strings.js');
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== src) {
      console.error('strings.js differs from the ARB files: run node tools/strings.mjs');
      process.exit(1);
    }
    console.log('strings.js matches the ARB files');
  } else {
    writeFileSync(file, src);
    console.log(`wrote ${file}`);
  }
}
