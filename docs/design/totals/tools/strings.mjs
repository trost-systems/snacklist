// Writes strings.js: every UI word the round shows, copied from the app's ARB files by key. The round adds no UI
// text of its own; verify.mjs checks that strings.js still equals the ARB files.
// Usage: node tools/strings.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const here = dirname(fileURLToPath(import.meta.url));
export const keys = [
  'tripTotal', 'subtotalsTotal', 'subtotalsUnpriced', 'subtotalsPriced', 'subtotalsAllBought', 'subtotalsBought',
  'subtotalsOpen', 'subtotalsJump', 'moneyAtLeast', 'moneyEstimate', 'noStore', 'priceAdd', 'recentlyUsed', 'addFieldHint',
  'tabList', 'tabHistory', 'tabMore', 'listEdit', 'itemsWord', 'shopRunning', 'shopEnd', 'categoryProduce',
  'categoryBakery', 'categoryChilled', 'categoryHousehold',
];
export const generate = (arbDir) => {
  const out = {};
  for (const lang of ['en', 'de']) {
    const arb = JSON.parse(readFileSync(join(arbDir, `app_${lang}.arb`), 'utf8'));
    out[lang] = Object.fromEntries(keys.map((k) => {
      if (!(k in arb)) throw new Error(`${k} is not in app_${lang}.arb`);
      return [k, arb[k]];
    }));
  }
  return `// Generated by tools/strings.mjs from app/l10n/app_<lang>.arb. Do not edit.\nexport const arb = ${JSON.stringify(out, null, 1)};\n`;
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = generate(join(here, '../../../../app/l10n'));
  const file = join(here, '../strings.js');
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== src) {
      console.error('strings.js differs from the ARB files: run node tools/strings.mjs');
      process.exit(1);
    }
    console.log('strings.js matches the ARB files');
  } else {
    writeFileSync(file, src);
    console.log(`wrote ${file}`);
  }
}
