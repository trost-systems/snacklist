// Writes palette.css from the app's own colour tokens (app/lib/design/tokens.g.dart, SnacklistColors.light and .dark),
// so every option draws with exactly today's palette. verify.mjs checks palette.css against tokens.g.dart and every
// colour the phones paint against this list.
// Usage: node tools/palette.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const here = dirname(fileURLToPath(import.meta.url));
export const readTokens = (dart) => {
  const out = {};
  for (const theme of ['light', 'dark']) {
    const block = dart.split(`static const ${theme} = SnacklistColors(`)[1].split(');')[0];
    out[theme] = Object.fromEntries([...block.matchAll(/(\w+): Color\(0xFF([0-9A-F]{6})\)/g)].map(([, k, v]) => [k, `#${v.toLowerCase()}`]));
  }
  return out;
};
const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
export const generate = (dart) => {
  const t = readTokens(dart);
  const block = (theme) => Object.entries(t[theme]).map(([k, v]) => `  --c-${kebab(k)}: ${v};`).join('\n');
  return `/* Generated by tools/palette.mjs from app/lib/design/tokens.g.dart. Do not edit. */\n.th-light {\n${block('light')}\n}\n.th-dark {\n${block('dark')}\n}\n`;
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = generate(readFileSync(join(here, '../../../../app/lib/design/tokens.g.dart'), 'utf8'));
  const file = join(here, '../palette.css');
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== src) {
      console.error('palette.css differs from tokens.g.dart: run node tools/palette.mjs');
      process.exit(1);
    }
    console.log('palette.css matches tokens.g.dart');
  } else {
    writeFileSync(file, src);
    console.log(`wrote ${file}`);
  }
}
