# Writes icons.js: SVG paths of the app's own Material icons, read from Flutter's MaterialIcons-Regular.otf.
# Usage: PYTHONPATH=<unzipped fonttools wheel> python3 tools/icons.py (needs ~/flutter)
import json, os, re, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

NAMES = ['expand_more', 'expand_less', 'unfold_more', 'shopping_cart_outlined', 'history', 'menu', 'add', 'remove', 'check',
         'close', 'chevron_right', 'chevron_left', 'arrow_back', 'mic_none', 'settings_outlined', 'storefront_outlined',
         'person_outline', 'group_outlined', 'help_outline', 'more_horiz', 'more_vert', 'search', 'receipt_long_outlined',
         'tune', 'language', 'lightbulb_outline', 'drag_handle', 'delete_outline', 'swap_horiz', 'list', 'checklist',
         'home_outlined', 'person_add_alt', 'feedback_outlined', 'star_outline', 'logout', 'arrow_drop_down', 'edit_outlined',
         'radio_button_unchecked', 'check_circle', 'check_box_outline_blank', 'check_box', 'circle_outlined', 'done_all',
         'shopping_basket_outlined', 'workspace_premium_outlined', 'keyboard_arrow_down', 'euro',
         'manage_accounts_outlined', 'key_outlined', 'insights_outlined', 'info_outline', 'privacy_tip_outlined',
         'article_outlined', 'description_outlined']
home = os.path.expanduser('~/flutter')
src = open(f'{home}/packages/flutter/lib/src/material/icons.dart').read()
font = TTFont(f'{home}/bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf')
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
upm = font['head'].unitsPerEm
out = {}
for name in NAMES:
    m = re.search(rf'static const IconData {name} = IconData\(\s*(0x[0-9a-f]+)', src)
    if not m:
        sys.exit(f'no icon {name}')
    pen = SVGPathPen(glyphs)
    s = 24 / upm
    glyphs[cmap[int(m.group(1), 16)]].draw(TransformPen(pen, (s, 0, 0, -s, 0, 24)))
    out[name] = pen.getCommands()
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, '..', 'icons.js'), 'w') as f:
    f.write("// Generated by tools/icons.py from Flutter's MaterialIcons-Regular.otf (the app's icon font). Do not edit.\n")
    f.write('export const icons = ' + json.dumps(out, indent=1) + ';\n')
print(f'wrote {len(out)} icons')
