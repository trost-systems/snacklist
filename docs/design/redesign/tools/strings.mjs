// Writes strings.js: every UI word the round takes from the app, copied from the ARB files by key, plus the few new
// words the options need (`proposed`, marked on the round page). verify.mjs checks strings.js against the ARB files.
// Usage: node tools/strings.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const here = dirname(fileURLToPath(import.meta.url));
export const keys = [
  'addFieldHint', 'recentlyUsed', 'noStore', 'tabList', 'tabHistory', 'tabMore', 'storesTitle', 'listEdit', 'storeAdd',
  'settingsTitle', 'language', 'helpRow', 'listMain', 'householdPageTitle', 'inviteMember', 'priceAdd', 'tripTotal',
  'subtotalsTotal', 'subtotalsUnpriced', 'moneyAtLeast', 'emptyList', 'account', 'hintsTitle', 'signOut', 'itemsWord',
  'listItemCount', 'householdMembers', 'listsTitle', 'shopAskTitle', 'shopAskYes', 'shopAskNo', 'shopAskMistake',
  'shopAskTakeBack', 'addSheetHint', 'suggestionRecent', 'suggestionHistory', 'feedbackHubRow', 'premiumTitle', 'done',
  'shopStartByHand', 'switcherInvite', 'accessTitle', 'analyticsSection', 'imprint', 'privacyPolicy', 'premiumTermsLink',
  'licenses', 'rateApp', 'appVersion',
];
// New words: the menus' own labels (RD2, RD4, RD6, RD7, RD8), RD8's "All" tab, RD5's and RD10's add button.
export const proposed = {
  en: { menu: 'Menu', households: 'Households', allStores: 'All', newList: 'New list', addItem: 'Add item', inCart: 'In the cart', listsAndHouseholds: 'Lists and households' },
  de: { menu: 'Menü', households: 'Haushalte', allStores: 'Alle', newList: 'Neue Liste', addItem: 'Artikel hinzufügen', inCart: 'Im Wagen', listsAndHouseholds: 'Listen und Haushalte' },
};
export const generate = (arbDir) => {
  const out = {};
  for (const lang of ['en', 'de']) {
    const arb = JSON.parse(readFileSync(join(arbDir, `app_${lang}.arb`), 'utf8'));
    out[lang] = Object.fromEntries(keys.map((k) => {
      if (!(k in arb)) throw new Error(`${k} is not in app_${lang}.arb`);
      return [k, arb[k]];
    }));
  }
  return `// Generated by tools/strings.mjs from app/l10n/app_<lang>.arb. Do not edit.\nexport const arb = ${JSON.stringify(out, null, 1)};\nexport const proposed = ${JSON.stringify(proposed, null, 1)};\n`;
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = generate(join(here, '../../../../app/l10n'));
  const file = join(here, '../strings.js');
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== src) {
      console.error('strings.js differs from the ARB files: run node tools/strings.mjs');
      process.exit(1);
    }
    console.log('strings.js matches the ARB files');
  } else {
    writeFileSync(file, src);
    console.log(`wrote ${file}`);
  }
}
