// Writes strings.js: every UI word the round takes from the app, copied from the ARB files by key, plus the few new
// words the options need (`proposed`, marked as such on the round page). verify.mjs checks strings.js against the ARB
// files.
// Usage: node tools/strings.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const here = dirname(fileURLToPath(import.meta.url));
export const keys = [
  'noStore', 'addFieldHint', 'tabList', 'tabHistory', 'tabMore', 'listEdit', 'itemsWord', 'shopRunning', 'shopEnd', 'priceAdd',
  'recentlyUsed', 'done', 'cancel', 'listMoveUp', 'listMoveDown', 'fieldName', 'fieldBrand', 'brandNone', 'itemQuantity',
  'fieldProperties', 'propertiesExample', 'claimMine', 'storesTitle', 'storeAdd', 'noStoreRowHint', 'storesHint',
  'categoryProduce', 'categoryBakery', 'categoryMeat', 'categoryChilled', 'categoryPantry', 'categorySweets', 'categoryFrozen',
  'categoryDrinks', 'categoryHousehold', 'categoryOther', 'dragCategory',
];
// New words: IO3's sort button, IO4's place chip and its first row, IO5's switch.
export const proposed = {
  en: { sortItems: 'Order', placeNextTo: 'Next to {name}', placeFirst: 'At the start', showCategories: 'Show categories' },
  de: { sortItems: 'Reihenfolge', placeNextTo: 'Neben {name}', placeFirst: 'Ganz vorne', showCategories: 'Kategorien zeigen' },
};
export const generate = (arbDir) => {
  const out = {};
  for (const lang of ['en', 'de']) {
    const arb = JSON.parse(readFileSync(join(arbDir, `app_${lang}.arb`), 'utf8'));
    out[lang] = Object.fromEntries(keys.map((k) => {
      if (!(k in arb)) throw new Error(`${k} is not in app_${lang}.arb`);
      return [k, arb[k]];
    }));
  }
  return `// Generated by tools/strings.mjs from app/l10n/app_<lang>.arb. Do not edit.\nexport const arb = ${JSON.stringify(out, null, 1)};\nexport const proposed = ${JSON.stringify(proposed, null, 1)};\n`;
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = generate(join(here, '../../../../app/l10n'));
  const file = join(here, '../strings.js');
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== src) {
      console.error('strings.js differs from the ARB files: run node tools/strings.mjs');
      process.exit(1);
    }
    console.log('strings.js matches the ARB files');
  } else {
    writeFileSync(file, src);
    console.log(`wrote ${file}`);
  }
}
